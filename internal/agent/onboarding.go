type metricsObservation struct {
	At time.Time
	OK bool
}

// inspectFiles reads only bounded, regular, explicitly configured local files.
// Heuristics are warnings, not proof that an external writer is absent.
func inspectFiles(paths []string) (code string, automated bool) {
	if len(paths) == 0 {
		return "files_not_configured", false
	}
	for _, path := range paths {
		f, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
		if err != nil {
			return "files_unreadable", automated
		}
		info, statErr := f.Stat()
		if statErr != nil || !info.Mode().IsRegular() || info.Size() > 1<<20 {
			f.Close()
			return "files_unreadable", automated
		}
		raw, readErr := io.ReadAll(io.LimitReader(f, 16<<10))
		f.Close()
		if readErr != nil {
			return "files_unreadable", automated
		}
		for _, line := range strings.Split(strings.ToLower(string(raw)), "\n") {
			line = strings.TrimSpace(line)
			if !strings.HasPrefix(line, "#") {
				continue
			}
			for _, marker := range []string{"ansible managed", "managed by ansible", "managed by puppet", "managed by chef", "generated by", "automatically generated", "do not edit", "haproxy ingress"} {
				automated = automated || strings.Contains(line, marker)
			}
		}
	}
	return "files_ready", automated
}

func configurationOwnershipAllows(c Config, files string, automated bool) bool {
	return files == "files_ready" && c.ConfigurationOwner != "external" && (!automated || c.ConfigurationOwner == "manager")
}

func configurationClient(c Config, runtime haproxyruntime.Client, allow bool) *dataplane.Client {
	raw, err := readPrivate(c.DataplaneCredentialsFile, 4096)
	if err != nil {
		return nil
	}
	var credentials dataplane.Credentials
	if json.Unmarshal(raw, &credentials) != nil {
		return nil
	}
	client, err := dataplane.New(c.DataplaneSocket, c.StateDir, credentials, allow, runtime)
	if err != nil {
		return nil
	}
	return client
}

func nodeSetup(c Config, d domain.Discovery, metrics *metricsObservation, files string, automated, admin bool) *domain.NodeSetup {
	report := &domain.NodeSetup{ObservedAtMS: time.Now().UnixMilli(), Owner: c.ConfigurationOwner}
	if report.Owner == "" {
		report.Owner = "unconfirmed"
	}
	add := func(name, code string) { report.Checks = append(report.Checks, domain.SetupResult(name, code)) }
	metricsCode := "metrics_pending"
	if metrics != nil {
		metricsCode = "metrics_unavailable"
		if metrics.OK && time.Since(metrics.At) <= 6*time.Second {
			metricsCode = "metrics_ready"
		}
	}
	add("metrics", metricsCode)
	runtimeCode := d.ErrorCode
	if runtimeCode == "" {
		runtimeCode = "runtime_ready"
	}
	add("discovery", runtimeCode)
	add("files", files)
	ownerCode := "owner_" + report.Owner
	if automated && c.ConfigurationOwner != "external" {
		ownerCode = "automation_detected"
	}
	add("ownership", ownerCode)
	runtimeControl := "runtime_control_disabled"
	if c.AllowRuntimeControl {
		switch {
		case d.ErrorCode != "" || files != "files_ready":
			runtimeControl = "runtime_control_unavailable"
		case !strings.HasPrefix(d.Version, "3.4."):
			runtimeControl = "runtime_version_unsupported"
		case !admin:
			runtimeControl = "runtime_admin_required"
		default:
			runtimeControl = "runtime_control_ready"
		}
	}
	add("runtime_control", runtimeControl)
	configControl := "configuration_control_disabled"
	if c.AllowConfigurationControl || c.DataplaneSocket != "" {
		switch {
		case c.AllowConfigurationControl && !configurationOwnershipAllows(c, files, automated):
			configControl = "configuration_owner_required"
		case d.Configuration != nil && d.Configuration.ErrorCode == "configuration_unsupported":
			configControl = "configuration_unsupported"
		case d.ErrorCode != "" || !strings.HasPrefix(d.Version, "3.4.") || d.Configuration == nil || !d.Configuration.Fresh(time.Now()):
			configControl = "configuration_unavailable"
		case !c.AllowConfigurationControl:
			configControl = "configuration_read_only"
		default:
			configControl = "configuration_control_ready"
		}
	}
	add("configuration_control", configControl)
	return report
}

// Preflight never enrolls, creates state, snapshots raw configuration, reloads
// HAProxy or issues a mutating Runtime/DPA request. Run as the intended agent
// user, with its mounts and network, to check the permissions it will receive.
func Preflight(ctx context.Context, c Config) (*domain.NodeSetup, error) {
	c, err := normalizeLocal(c)
	if err != nil {
		return nil, err
	}
	metricsCtx, cancel := context.WithTimeout(ctx, 4*time.Second)
	_, scrapeErr := (&telemetry.Collector{URL: c.MetricsURL}).Collect(metricsCtx, time.Now())
	cancel()
	metrics := &metricsObservation{At: time.Now(), OK: scrapeErr == nil}
	files, automated := inspectFiles(c.ConfigFiles)
	runtime := haproxyruntime.Client{Socket: c.RuntimeSocket, ConfigFiles: c.ConfigFiles}
	runtimeCtx, cancel := context.WithTimeout(ctx, 3*time.Second)
	d := runtime.Discover(runtimeCtx)
	admin := c.AllowRuntimeControl && d.ErrorCode == "" && runtime.AdminAccess(runtimeCtx)
	cancel()
	if c.DataplaneSocket != "" {
		if client := configurationClient(c, runtime, false); client != nil {
			configCtx, stop := context.WithTimeout(ctx, 3*time.Second)
			if c.TLSPolicyFile == "" || client.LoadTLSPolicy(c.TLSPolicyFile) == nil {
				d.Configuration = client.Inspect(configCtx)
			}
			stop()
			client.Close()
		}
	}
	return nodeSetup(c, d, metrics, files, automated, admin), nil
}

// PreflightOK allows intentional observation-only/external-owner installs while
// rejecting failed prerequisites and requested controls that are unavailable.
func PreflightOK(report *domain.NodeSetup) bool {
	if report == nil || !report.Valid() {
		return false
	}
	for _, check := range report.Checks {
		if check.Status == "error" || check.Status == "pending" || (check.Status == "blocked" && check.Name != "ownership") {
			return false
		}
	}
	return true
}
