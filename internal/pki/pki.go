// Package pki issues installation-local identities. Enrollment never receives a
// private key: agents generate a key and submit a signed CSR.
package pki

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/ecraela/fleet/internal/domain"
)

const CertificateLifetime = 7 * 24 * time.Hour

type Authority struct {
	Certificate *x509.Certificate
	PEM         []byte
	key         crypto.Signer
}

// Init creates a new installation; existing state is deliberately not replaced.
func Init(dir string, dnsNames []string, ips []net.IP) error {
	if len(dnsNames) == 0 && len(ips) == 0 {
		return errors.New("at least one server DNS name or IP is required")
	}
	if err := os.Mkdir(dir, 0700); err != nil {
		return fmt.Errorf("create new PKI directory: %w", err)
	}
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	now := time.Now().UTC()
	ca := &x509.Certificate{SerialNumber: serial(), Subject: pkix.Name{CommonName: "Converge HAProxy installation CA"},
		NotBefore: now.Add(-time.Minute), NotAfter: now.AddDate(10, 0, 0), IsCA: true, BasicConstraintsValid: true,
		KeyUsage: x509.KeyUsageCertSign | x509.KeyUsageCRLSign}
	der, err := x509.CreateCertificate(rand.Reader, ca, ca, &key.PublicKey, key)
	if err != nil {
		return err
	}
	if err := writeKeyPair(dir, "ca", der, key); err != nil {
		return err
	}
	// Parsing preserves the SubjectKeyId generated by CreateCertificate, so
	// server leaves receive the AuthorityKeyId required by strict TLS clients.
	ca, err = x509.ParseCertificate(der)
	if err != nil {
		return err
	}
	serverKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	server := &x509.Certificate{SerialNumber: serial(), Subject: pkix.Name{CommonName: "Converge HAProxy manager"},
		NotBefore: now.Add(-time.Minute), NotAfter: now.AddDate(1, 0, 0), DNSNames: dnsNames, IPAddresses: ips,
		KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth}}
	der, err = x509.CreateCertificate(rand.Reader, server, ca, &serverKey.PublicKey, key)
	if err != nil {
		return err
	}
	return writeKeyPair(dir, "server", der, serverKey)
}

func Load(dir string, signer bool) (*Authority, error) {
	certPEM, err := os.ReadFile(filepath.Join(dir, "ca.crt"))
	if err != nil {
		return nil, err
	}
	block, _ := pem.Decode(certPEM)
	if block == nil || block.Type != "CERTIFICATE" {
		return nil, errors.New("invalid installation CA")
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil || !cert.IsCA {
		return nil, errors.New("invalid installation CA")
	}
	a := &Authority{Certificate: cert, PEM: certPEM}
	if signer {
		pair, err := tls.LoadX509KeyPair(filepath.Join(dir, "ca.crt"), filepath.Join(dir, "ca.key"))
		if err != nil {
			return nil, err
		}
		var ok bool
		a.key, ok = pair.PrivateKey.(crypto.Signer)
		if !ok {
			return nil, errors.New("unsupported CA key")
		}
	}
	return a, nil
}

func (a *Authority) TLSConfig(requireClient bool) *tls.Config {
	pool := x509.NewCertPool()
	pool.AddCert(a.Certificate)
	auth := tls.VerifyClientCertIfGiven
	if requireClient {
		auth = tls.RequireAndVerifyClientCert
	}
	return &tls.Config{MinVersion: tls.VersionTLS13, ClientCAs: pool, ClientAuth: auth}
}

func (a *Authority) Issue(csrPEM string, node domain.Node, now time.Time) ([]byte, error) {
	if a.key == nil {
		return nil, errors.New("CA signing is unavailable")
	}
	if !domain.ValidID(node.ID) || !domain.ValidID(node.OrganizationID) || !domain.ValidID(node.ClusterID) {
		return nil, domain.ErrInvalidInput
	}
	block, rest := pem.Decode([]byte(csrPEM))
	if block == nil || block.Type != "CERTIFICATE REQUEST" || len(strings.TrimSpace(string(rest))) != 0 {
		return nil, domain.ErrInvalidInput
	}
	csr, err := x509.ParseCertificateRequest(block.Bytes)
	if err != nil || csr.CheckSignature() != nil {
		return nil, domain.ErrInvalidInput
	}
	// Pin the first protocol to P-256. Ignore all CSR-requested identities,
	// extensions and CA flags; only the verified public key is used.
	key, ok := csr.PublicKey.(*ecdsa.PublicKey)
	if !ok || key.Curve != elliptic.P256() {
		return nil, domain.ErrInvalidInput
	}
	identity := &url.URL{Scheme: "spiffe", Host: "converge-haproxy", Path: fmt.Sprintf("/organizations/%s/clusters/%s/nodes/%s", node.OrganizationID, node.ClusterID, node.ID)}
	expires := now.Add(CertificateLifetime)
	if expires.After(a.Certificate.NotAfter) {
		expires = a.Certificate.NotAfter
	}
	if !expires.After(now) {
		return nil, errors.New("installation CA expired")
	}
	cert := &x509.Certificate{SerialNumber: serial(), Subject: pkix.Name{CommonName: node.ID},
		NotBefore: now.Add(-time.Minute), NotAfter: expires, URIs: []*url.URL{identity},
		KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth}}
	der, err := x509.CreateCertificate(rand.Reader, cert, a.Certificate, csr.PublicKey, a.key)
	if err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), nil
}

// Identity rejects certificates with ambiguous or noncanonical application IDs.
// The TLS layer must verify the chain and client-auth purpose before calling it.
func Identity(cert *x509.Certificate) (domain.Node, error) {
	if cert == nil || len(cert.URIs) != 1 {
		return domain.Node{}, domain.ErrInvalidInput
	}
	u := cert.URIs[0]
	parts := strings.Split(u.Path, "/")
	if u.Scheme != "spiffe" || u.Host != "converge-haproxy" || u.RawQuery != "" || u.Fragment != "" || u.User != nil ||
		len(parts) != 7 || parts[0] != "" || parts[1] != "organizations" || parts[3] != "clusters" || parts[5] != "nodes" ||
		!domain.ValidID(parts[2]) || !domain.ValidID(parts[4]) || !domain.ValidID(parts[6]) {
		return domain.Node{}, domain.ErrInvalidInput
	}
	return domain.Node{OrganizationID: parts[2], ClusterID: parts[4], ID: parts[6]}, nil
}

func serial() *big.Int {
	b := make([]byte, 20)
	_, _ = rand.Read(b)
	b[0] &= 0x7f
	b[19] |= 1
	return new(big.Int).SetBytes(b)
}

func writeKeyPair(dir, name string, certDER []byte, key crypto.Signer) error {
	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return err
	}
	if err := writeNew(filepath.Join(dir, name+".key"), pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER}), 0600); err != nil {
		return err
	}
	return writeNew(filepath.Join(dir, name+".crt"), pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: certDER}), 0644)
}

func writeNew(path string, data []byte, mode os.FileMode) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := f.Write(data); err != nil {
		return err
	}
	return f.Sync()
}
